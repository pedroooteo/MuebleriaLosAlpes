/

CREATE OR REPLACE PACKAGE BODY PKG_CLIENTES AS
    PROCEDURE PR_LISTAR_CIUDADES(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
        SELECT CI.ID_CIUDAD, CI.NOMBRE AS CIUDAD, D.NOMBRE AS DEPARTAMENTO, P.NOMBRE AS PAIS
        FROM CIUDADES CI JOIN DEPARTAMENTOS D ON CI.ID_DEPTO = D.ID_DEPTO JOIN PAISES P ON D.ID_PAIS = P.ID_PAIS ORDER BY P.NOMBRE, D.NOMBRE, CI.NOMBRE;
    END PR_LISTAR_CIUDADES;

    PROCEDURE PR_OBTENER_PERFIL(p_id_cliente IN NUMBER, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
        SELECT CL.ID_CLIENTE, CL.NOMBRE_COMPLETO, CL.EMAIL, CL.TEL_RESIDENCIA, CL.TEL_CELULAR, CL.DIRECCION, CL.TIPO_DOC, CL.NUM_DOC,
               CL.TIPO_PERSONA, CL.NIT, CL.PROFESION, CI.NOMBRE AS CIUDAD, D.NOMBRE AS DEPARTAMENTO
        FROM CLIENTES CL LEFT JOIN CIUDADES CI ON CL.ID_CIUDAD = CI.ID_CIUDAD LEFT JOIN DEPARTAMENTOS D ON CI.ID_DEPTO = D.ID_DEPTO
        WHERE CL.ID_CLIENTE = p_id_cliente;
    END PR_OBTENER_PERFIL;

    PROCEDURE PR_BUSCAR_CLIENTES(p_criterio IN VARCHAR2, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
        SELECT CL.ID_CLIENTE, CL.NUM_DOC, CL.NOMBRE_COMPLETO, CL.EMAIL, CL.TEL_RESIDENCIA, CL.TIPO_PERSONA, CL.ESTADO, CI.NOMBRE AS CIUDAD,
               (SELECT COUNT(*) FROM COMPRAS WHERE ID_CLIENTE = CL.ID_CLIENTE) AS TOTAL_COMPRAS
        FROM CLIENTES CL LEFT JOIN CIUDADES CI ON CL.ID_CIUDAD = CI.ID_CIUDAD
        WHERE (p_criterio IS NULL OR UPPER(CL.NUM_DOC) LIKE '%'||UPPER(p_criterio)||'%' OR UPPER(CL.NOMBRE_COMPLETO) LIKE '%'||UPPER(p_criterio)||'%' OR UPPER(CL.EMAIL) LIKE '%'||UPPER(p_criterio)||'%')
        ORDER BY CL.NOMBRE_COMPLETO;
    END PR_BUSCAR_CLIENTES;

    PROCEDURE PR_ELIMINAR_CLIENTE(p_id_cliente IN NUMBER) IS
        v_compras NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_compras FROM COMPRAS WHERE ID_CLIENTE = p_id_cliente;
        IF v_compras > 0 THEN RAISE_APPLICATION_ERROR(-20012, 'No se puede eliminar: el cliente tiene compras registradas'); END IF;
        DELETE FROM DETALLE_CARRITO DC WHERE DC.ID_CARRITO IN (SELECT ID_CARRITO FROM CARRITO WHERE ID_CLIENTE = p_id_cliente);
        DELETE FROM CARRITO WHERE ID_CLIENTE = p_id_cliente;
        DELETE FROM USUARIOS_SISTEMA WHERE ID_CLIENTE = p_id_cliente;
        DELETE FROM CLIENTES WHERE ID_CLIENTE = p_id_cliente;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END PR_ELIMINAR_CLIENTE;
END PKG_CLIENTES;
