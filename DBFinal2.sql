    PROCEDURE PR_EFECTUAR_COMPRA(p_id_cliente IN NUMBER, p_forma_pago IN VARCHAR2, p_numero_orden OUT VARCHAR2);
    PROCEDURE PR_HISTORIAL_COMPRAS(p_id_cliente IN NUMBER, p_cursor OUT SYS_REFCURSOR);
END PKG_COMPRAS;
/

CREATE OR REPLACE PACKAGE BODY PKG_COMPRAS AS
    PROCEDURE PR_EFECTUAR_COMPRA(p_id_cliente IN NUMBER, p_forma_pago IN VARCHAR2, p_numero_orden OUT VARCHAR2) IS
        v_id_carrito NUMBER; v_id_compra NUMBER; v_total NUMBER; v_orden VARCHAR2(50);
    BEGIN
        SELECT ID_CARRITO INTO v_id_carrito FROM CARRITO WHERE ID_CLIENTE = p_id_cliente AND ESTADO = 'ACTIVO';
        FOR rec IN (SELECT DC.ID_MUEBLE, DC.CANTIDAD, M.STOCK_DISPONIBLE FROM DETALLE_CARRITO DC JOIN MUEBLES M ON DC.ID_MUEBLE = M.ID_MUEBLE WHERE DC.ID_CARRITO = v_id_carrito FOR UPDATE) LOOP
            IF rec.STOCK_DISPONIBLE < rec.CANTIDAD THEN RAISE_APPLICATION_ERROR(-20005, 'Stock insuficiente para mueble ID: ' || rec.ID_MUEBLE); END IF;
        END LOOP;
        SELECT SUM(SUBTOTAL) INTO v_total FROM DETALLE_CARRITO WHERE ID_CARRITO = v_id_carrito;
        v_orden := 'ORD-' || TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS');
        INSERT INTO COMPRAS (NUMERO_ORDEN, ID_CLIENTE, TOTAL, FORMA_PAGO, ESTADO) VALUES (v_orden, p_id_cliente, v_total, p_forma_pago, 'PAGADO') RETURNING ID_COMPRA INTO v_id_compra;
        INSERT INTO DETALLE_COMPRA (ID_COMPRA, ID_MUEBLE, CANTIDAD, PRECIO_UNITARIO, SUBTOTAL) SELECT v_id_compra, ID_MUEBLE, CANTIDAD, PRECIO_UNITARIO, SUBTOTAL FROM DETALLE_CARRITO WHERE ID_CARRITO = v_id_carrito;
        FOR rec IN (SELECT ID_MUEBLE, CANTIDAD FROM DETALLE_CARRITO WHERE ID_CARRITO = v_id_carrito) LOOP
            UPDATE MUEBLES SET STOCK_DISPONIBLE = STOCK_DISPONIBLE - rec.CANTIDAD WHERE ID_MUEBLE = rec.ID_MUEBLE;
            INSERT INTO INVENTARIO_MOVIMIENTOS (ID_MUEBLE, TIPO_MOVIMIENTO, CANTIDAD, DESCRIPCION) VALUES (rec.ID_MUEBLE, 'SALIDA', rec.CANTIDAD, 'Compra ' || v_orden);
        END LOOP;
        UPDATE CARRITO SET ESTADO = 'COMPRADO' WHERE ID_CARRITO = v_id_carrito;
        p_numero_orden := v_orden;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END PR_EFECTUAR_COMPRA;

    PROCEDURE PR_HISTORIAL_COMPRAS(p_id_cliente IN NUMBER, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
        SELECT ID_COMPRA, NUMERO_ORDEN, TO_CHAR(FECHA_COMPRA, 'DD/MM/YYYY HH24:MI') AS FECHA_COMPRA, TOTAL, FORMA_PAGO, ESTADO
        FROM COMPRAS WHERE ID_CLIENTE = p_id_cliente ORDER BY FECHA_COMPRA DESC;
    END PR_HISTORIAL_COMPRAS;
END PKG_COMPRAS;
