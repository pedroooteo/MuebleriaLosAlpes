    PROCEDURE PR_AGREGAR_AL_CARRITO(p_id_cliente IN NUMBER, p_id_mueble IN NUMBER, p_cantidad IN NUMBER);
    PROCEDURE PR_VER_CARRITO(p_id_cliente IN NUMBER, p_cursor OUT SYS_REFCURSOR);
    PROCEDURE PR_ELIMINAR_DEL_CARRITO(p_id_detalle IN NUMBER);
END PKG_CARRITO;
/

CREATE OR REPLACE PACKAGE BODY PKG_CARRITO AS
    PROCEDURE PR_AGREGAR_AL_CARRITO(p_id_cliente IN NUMBER, p_id_mueble IN NUMBER, p_cantidad IN NUMBER) IS
        v_id_carrito NUMBER; v_id_detalle NUMBER; v_precio NUMBER(12,2);
    BEGIN
        SELECT PRECIO_VENTA INTO v_precio FROM MUEBLES WHERE ID_MUEBLE = p_id_mueble;
        BEGIN
            SELECT ID_CARRITO INTO v_id_carrito FROM CARRITO WHERE ID_CLIENTE = p_id_cliente AND ESTADO = 'ACTIVO' AND ROWNUM = 1;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            INSERT INTO CARRITO (ID_CLIENTE, ESTADO) VALUES (p_id_cliente, 'ACTIVO') RETURNING ID_CARRITO INTO v_id_carrito;
        END;
        BEGIN
            SELECT ID_DETALLE_CARRITO INTO v_id_detalle FROM DETALLE_CARRITO WHERE ID_CARRITO = v_id_carrito AND ID_MUEBLE = p_id_mueble;
            UPDATE DETALLE_CARRITO SET CANTIDAD = CANTIDAD + p_cantidad, SUBTOTAL = (CANTIDAD + p_cantidad) * v_precio WHERE ID_DETALLE_CARRITO = v_id_detalle;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            INSERT INTO DETALLE_CARRITO (ID_CARRITO, ID_MUEBLE, CANTIDAD, PRECIO_UNITARIO, SUBTOTAL) VALUES (v_id_carrito, p_id_mueble, p_cantidad, v_precio, p_cantidad * v_precio);
        END;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END PR_AGREGAR_AL_CARRITO;

    PROCEDURE PR_VER_CARRITO(p_id_cliente IN NUMBER, p_cursor OUT SYS_REFCURSOR) IS
        v_id_carrito NUMBER := NULL;
    BEGIN
        BEGIN
            SELECT ID_CARRITO INTO v_id_carrito FROM CARRITO WHERE ID_CLIENTE = p_id_cliente AND ESTADO = 'ACTIVO' AND ROWNUM = 1;
        EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
        END;
        OPEN p_cursor FOR
        SELECT DC.ID_DETALLE_CARRITO, M.ID_MUEBLE, M.REFERENCIA, M.NOMBRE, DC.CANTIDAD, DC.PRECIO_UNITARIO, DC.SUBTOTAL
        FROM DETALLE_CARRITO DC JOIN MUEBLES M ON DC.ID_MUEBLE = M.ID_MUEBLE WHERE DC.ID_CARRITO = v_id_carrito;
    END PR_VER_CARRITO;

    PROCEDURE PR_ELIMINAR_DEL_CARRITO(p_id_detalle IN NUMBER) IS
    BEGIN
        DELETE FROM DETALLE_CARRITO WHERE ID_DETALLE_CARRITO = p_id_detalle;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END PR_ELIMINAR_DEL_CARRITO;
END PKG_CARRITO;
