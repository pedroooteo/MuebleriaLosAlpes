    PROCEDURE PR_REPORTE_ACTIVIDAD(p_fecha_ini IN DATE, p_fecha_fin IN DATE, p_cursor OUT SYS_REFCURSOR);
    PROCEDURE PR_REPORTE_RETENCION(p_cursor OUT SYS_REFCURSOR);
    PROCEDURE PR_REPORTE_COHORTE(p_cursor OUT SYS_REFCURSOR);
    PROCEDURE PR_REPORTE_REMARKETING(p_cursor OUT SYS_REFCURSOR);
END PKG_REPORTES;
/

CREATE OR REPLACE PACKAGE BODY PKG_REPORTES AS
    PROCEDURE PR_VENTAS_DIARIAS(p_fecha_ini IN DATE, p_fecha_fin IN DATE, p_id_ciudad IN NUMBER DEFAULT NULL, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT M.TIPO, TO_CHAR(C.FECHA_COMPRA, 'DD/MM/YYYY') AS FECHA, COUNT(DISTINCT C.ID_COMPRA) AS TOTAL_ORDENES, SUM(DC.CANTIDAD) AS UNIDADES_VENDIDAS, SUM(DC.SUBTOTAL) AS INGRESOS
        FROM COMPRAS C JOIN DETALLE_COMPRA DC ON C.ID_COMPRA = DC.ID_COMPRA JOIN MUEBLES M ON DC.ID_MUEBLE = M.ID_MUEBLE JOIN CLIENTES CL ON C.ID_CLIENTE = CL.ID_CLIENTE
        WHERE C.FECHA_COMPRA BETWEEN p_fecha_ini AND p_fecha_fin + 1 AND C.ESTADO = 'PAGADO' AND (p_id_ciudad IS NULL OR CL.ID_CIUDAD = p_id_ciudad)
        GROUP BY M.TIPO, TO_CHAR(C.FECHA_COMPRA, 'DD/MM/YYYY') ORDER BY TO_DATE(TO_CHAR(C.FECHA_COMPRA, 'DD/MM/YYYY'), 'DD/MM/YYYY'), M.TIPO;
    END PR_VENTAS_DIARIAS;

    PROCEDURE PR_PRODUCTO_TOP(p_fecha_ini IN DATE, p_fecha_fin IN DATE, p_id_ciudad IN NUMBER DEFAULT NULL, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT M.ID_MUEBLE, M.REFERENCIA, M.NOMBRE, M.TIPO, SUM(DC.CANTIDAD) AS UNIDADES_VENDIDAS, SUM(DC.SUBTOTAL) AS INGRESOS_TOTALES, COUNT(DISTINCT C.ID_COMPRA) AS ORDENES
        FROM COMPRAS C JOIN DETALLE_COMPRA DC ON C.ID_COMPRA = DC.ID_COMPRA JOIN MUEBLES M ON DC.ID_MUEBLE = M.ID_MUEBLE JOIN CLIENTES CL ON C.ID_CLIENTE = CL.ID_CLIENTE
        WHERE C.FECHA_COMPRA BETWEEN p_fecha_ini AND p_fecha_fin + 1 AND C.ESTADO = 'PAGADO' AND (p_id_ciudad IS NULL OR CL.ID_CIUDAD = p_id_ciudad)
        GROUP BY M.ID_MUEBLE, M.REFERENCIA, M.NOMBRE, M.TIPO ORDER BY UNIDADES_VENDIDAS DESC;
    END PR_PRODUCTO_TOP;

    PROCEDURE PR_HISTORIAL_CLIENTE_ADMIN(p_id_cliente IN NUMBER, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT C.NUMERO_ORDEN, TO_CHAR(C.FECHA_COMPRA,'DD/MM/YYYY HH24:MI') AS FECHA, C.TOTAL, C.FORMA_PAGO, C.ESTADO, CL.NOMBRE_COMPLETO, CL.EMAIL,
        (SELECT LISTAGG(M.NOMBRE || ' x'||DC2.CANTIDAD, ', ') FROM DETALLE_COMPRA DC2 JOIN MUEBLES M ON DC2.ID_MUEBLE=M.ID_MUEBLE WHERE DC2.ID_COMPRA = C.ID_COMPRA) AS PRODUCTOS
        FROM COMPRAS C JOIN CLIENTES CL ON C.ID_CLIENTE = CL.ID_CLIENTE WHERE C.ID_CLIENTE = p_id_cliente ORDER BY C.FECHA_COMPRA DESC;
    END PR_HISTORIAL_CLIENTE_ADMIN;

    PROCEDURE PR_CIERRE_CAJAS(p_fecha_ini IN DATE, p_fecha_fin IN DATE, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT C.FORMA_PAGO, COUNT(*) AS TOTAL_TRANSACCIONES, SUM(C.TOTAL) AS INGRESOS_TOTALES, MIN(C.TOTAL) AS VENTA_MINIMA, MAX(C.TOTAL) AS VENTA_MAXIMA, ROUND(AVG(C.TOTAL), 2) AS PROMEDIO_VENTA
        FROM COMPRAS C WHERE C.FECHA_COMPRA BETWEEN p_fecha_ini AND p_fecha_fin + 1 AND C.ESTADO = 'PAGADO' GROUP BY C.FORMA_PAGO ORDER BY INGRESOS_TOTALES DESC;
    END PR_CIERRE_CAJAS;

    PROCEDURE PR_REPORTE_LTV(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT CL.ID_CLIENTE, CL.NOMBRE_COMPLETO, CL.EMAIL, COUNT(C.ID_COMPRA) AS TOTAL_COMPRAS, NVL(SUM(C.TOTAL), 0) AS LTV_TOTAL, ROUND(NVL(AVG(C.TOTAL), 0), 2) AS TICKET_PROMEDIO, TO_CHAR(MIN(C.FECHA_COMPRA), 'DD/MM/YYYY') AS PRIMERA_COMPRA, TO_CHAR(MAX(C.FECHA_COMPRA), 'DD/MM/YYYY') AS ULTIMA_COMPRA
        FROM CLIENTES CL LEFT JOIN COMPRAS C ON CL.ID_CLIENTE = C.ID_CLIENTE AND C.ESTADO = 'PAGADO' GROUP BY CL.ID_CLIENTE, CL.NOMBRE_COMPLETO, CL.EMAIL ORDER BY LTV_TOTAL DESC;
    END PR_REPORTE_LTV;

    PROCEDURE PR_REPORTE_ACTIVIDAD(p_fecha_ini IN DATE, p_fecha_fin IN DATE, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT TO_CHAR(C.FECHA_COMPRA, 'YYYY-MM') AS MES, COUNT(DISTINCT C.ID_CLIENTE) AS CLIENTES_ACTIVOS, COUNT(C.ID_COMPRA) AS COMPRAS, SUM(C.TOTAL) AS INGRESOS
        FROM COMPRAS C WHERE C.FECHA_COMPRA BETWEEN p_fecha_ini AND p_fecha_fin + 1 AND C.ESTADO = 'PAGADO' GROUP BY TO_CHAR(C.FECHA_COMPRA, 'YYYY-MM') ORDER BY MES;
    END PR_REPORTE_ACTIVIDAD;

    PROCEDURE PR_REPORTE_RETENCION(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT CASE WHEN TOTAL_COMPRAS = 1 THEN 'Una compra' WHEN TOTAL_COMPRAS BETWEEN 2 AND 3 THEN '2-3 compras' WHEN TOTAL_COMPRAS BETWEEN 4 AND 6 THEN '4-6 compras' ELSE '7+ compras' END AS SEGMENTO, COUNT(*) AS CLIENTES, ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER(), 1) AS PORCENTAJE
        FROM (SELECT ID_CLIENTE, COUNT(*) AS TOTAL_COMPRAS FROM COMPRAS WHERE ESTADO = 'PAGADO' GROUP BY ID_CLIENTE) SUB GROUP BY CASE WHEN TOTAL_COMPRAS = 1 THEN 'Una compra' WHEN TOTAL_COMPRAS BETWEEN 2 AND 3 THEN '2-3 compras' WHEN TOTAL_COMPRAS BETWEEN 4 AND 6 THEN '4-6 compras' ELSE '7+ compras' END ORDER BY MIN(TOTAL_COMPRAS);
    END PR_REPORTE_RETENCION;

    PROCEDURE PR_REPORTE_COHORTE(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT TO_CHAR(PRIMERA_COMPRA, 'YYYY-MM') AS COHORTE, COUNT(DISTINCT ID_CLIENTE) AS CLIENTES_NUEVOS, SUM(TOTAL_COMPRAS) AS COMPRAS_TOTALES, ROUND(AVG(LTV), 2) AS LTV_PROMEDIO
        FROM (SELECT ID_CLIENTE, MIN(FECHA_COMPRA) AS PRIMERA_COMPRA, COUNT(*) AS TOTAL_COMPRAS, SUM(TOTAL) AS LTV FROM COMPRAS WHERE ESTADO = 'PAGADO' GROUP BY ID_CLIENTE) SUB GROUP BY TO_CHAR(PRIMERA_COMPRA, 'YYYY-MM') ORDER BY COHORTE;
    END PR_REPORTE_COHORTE;

    PROCEDURE PR_REPORTE_REMARKETING(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT CL.ID_CLIENTE, CL.NOMBRE_COMPLETO, CL.EMAIL, TO_CHAR(CA.FECHA_CREACION, 'DD/MM/YYYY') AS FECHA_CARRITO, COUNT(DC.ID_DETALLE_CARRITO) AS ITEMS_EN_CARRITO, SUM(DC.SUBTOTAL) AS VALOR_CARRITO
        FROM CARRITO CA JOIN DETALLE_CARRITO DC ON CA.ID_CARRITO = DC.ID_CARRITO JOIN CLIENTES CL ON CA.ID_CLIENTE = CL.ID_CLIENTE WHERE CA.ESTADO = 'ACTIVO' GROUP BY CL.ID_CLIENTE, CL.NOMBRE_COMPLETO, CL.EMAIL, CA.FECHA_CREACION ORDER BY VALOR_CARRITO DESC;
    END PR_REPORTE_REMARKETING;
END PKG_REPORTES;
