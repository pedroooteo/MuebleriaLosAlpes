CREATE OR REPLACE PACKAGE BODY PKG_SEGURIDAD AS
    PROCEDURE PR_REGISTRAR_CLIENTE_USUARIO(
        p_tipo_doc IN VARCHAR2, p_num_doc IN VARCHAR2, p_nombre IN VARCHAR2,
        p_tel_residencia IN VARCHAR2, p_tel_celular IN VARCHAR2 DEFAULT NULL,
        p_direccion IN VARCHAR2, p_id_ciudad IN NUMBER, p_email IN VARCHAR2,
        p_profesion IN VARCHAR2 DEFAULT NULL, p_tipo_persona IN VARCHAR2,
        p_nit IN VARCHAR2 DEFAULT NULL, p_username IN VARCHAR2, p_password_hash IN VARCHAR2
    ) IS
        v_id_cliente NUMBER;
        v_id_rol NUMBER;
    BEGIN
        INSERT INTO CLIENTES (TIPO_DOC, NUM_DOC, NOMBRE_COMPLETO, TEL_RESIDENCIA, TEL_CELULAR,
            DIRECCION, ID_CIUDAD, EMAIL, PROFESION, TIPO_PERSONA, NIT)
        VALUES (p_tipo_doc, p_num_doc, p_nombre, p_tel_residencia, p_tel_celular,
            p_direccion, p_id_ciudad, p_email, p_profesion, p_tipo_persona, p_nit)
        RETURNING ID_CLIENTE INTO v_id_cliente;
        
        SELECT ID_ROL INTO v_id_rol FROM ROLES WHERE NOMBRE_ROL = 'CLIENTE';
        
        INSERT INTO USUARIOS_SISTEMA (USERNAME, PASSWORD_HASH, ID_CLIENTE, ID_ROL)
        VALUES (p_username, p_password_hash, v_id_cliente, v_id_rol);
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END PR_REGISTRAR_CLIENTE_USUARIO;

    FUNCTION FN_VALIDAR_LOGIN(p_username IN VARCHAR2, p_password_hash IN VARCHAR2) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USUARIOS_SISTEMA
        WHERE USERNAME = p_username AND PASSWORD_HASH = p_password_hash AND ESTADO = 'ACTIVO';
        IF v_count = 1 THEN
            UPDATE USUARIOS_SISTEMA SET ULTIMO_LOGIN = SYSDATE WHERE USERNAME = p_username;
            COMMIT;
        END IF;
        RETURN v_count;
    END FN_VALIDAR_LOGIN;

    PROCEDURE PR_DATOS_USUARIO(p_username IN VARCHAR2, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
        SELECT U.ID_USUARIO, U.USERNAME, U.ID_CLIENTE, U.ID_ROL, R.NOMBRE_ROL
        FROM USUARIOS_SISTEMA U
        JOIN ROLES R ON U.ID_ROL = R.ID_ROL
        WHERE U.USERNAME = p_username AND U.ESTADO = 'ACTIVO';
    END PR_DATOS_USUARIO;
END PKG_SEGURIDAD;
