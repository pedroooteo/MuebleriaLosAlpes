CREATE OR REPLACE PACKAGE BODY PKG_MUEBLES AS
    PROCEDURE PR_CONSULTAR_MUEBLES(p_criterio IN VARCHAR2 DEFAULT NULL, p_tipo IN VARCHAR2 DEFAULT NULL, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
        SELECT ID_MUEBLE, REFERENCIA, NOMBRE, TIPO, PRECIO_VENTA, STOCK_DISPONIBLE, FOTO_URL, MATERIAL, COLOR, DESCRIPCION
        FROM MUEBLES
        WHERE (p_criterio IS NULL OR UPPER(NOMBRE) LIKE '%'||UPPER(p_criterio)||'%' OR UPPER(REFERENCIA) LIKE '%'||UPPER(p_criterio)||'%')
          AND (p_tipo IS NULL OR TIPO = p_tipo) AND STOCK_DISPONIBLE > 0;
    END PR_CONSULTAR_MUEBLES;

    PROCEDURE PR_BUSCAR_MUEBLES_ADMIN(p_criterio IN VARCHAR2 DEFAULT NULL, p_tipo IN VARCHAR2 DEFAULT NULL, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
        SELECT M.ID_MUEBLE, M.REFERENCIA, M.NOMBRE, M.TIPO, M.PRECIO_VENTA, M.STOCK_DISPONIBLE, M.FOTO_URL, M.MATERIAL, M.COLOR,
               M.ALTO_CM, M.ANCHO_CM, M.PROFUNDIDAD_CM, M.PESO_GRAMOS, C.NOMBRE AS CATEGORIA, M.DESCRIPCION
        FROM MUEBLES M
        LEFT JOIN CATEGORIAS C ON M.ID_CATEGORIA = C.ID_CATEGORIA
        WHERE (p_criterio IS NULL OR UPPER(M.NOMBRE) LIKE '%'||UPPER(p_criterio)||'%' OR UPPER(M.REFERENCIA) LIKE '%'||UPPER(p_criterio)||'%')
          AND (p_tipo IS NULL OR M.TIPO = p_tipo) ORDER BY M.FECHA_CREACION DESC;
    END PR_BUSCAR_MUEBLES_ADMIN;

    PROCEDURE PR_CREAR_MUEBLE(
        p_referencia IN VARCHAR2, p_nombre IN VARCHAR2, p_descripcion IN CLOB, p_tipo IN VARCHAR2, p_id_categoria IN NUMBER, p_material IN VARCHAR2,
        p_alto_cm IN NUMBER, p_ancho_cm IN NUMBER, p_profundidad_cm IN NUMBER, p_color IN VARCHAR2, p_peso_gramos IN NUMBER, p_foto_url IN VARCHAR2,
        p_precio IN NUMBER, p_stock IN NUMBER
    ) IS
    BEGIN
        INSERT INTO MUEBLES (REFERENCIA, NOMBRE, DESCRIPCION, TIPO, ID_CATEGORIA, MATERIAL, ALTO_CM, ANCHO_CM, PROFUNDIDAD_CM, COLOR, PESO_GRAMOS, FOTO_URL, PRECIO_VENTA, STOCK_DISPONIBLE)
        VALUES (p_referencia, p_nombre, p_descripcion, p_tipo, p_id_categoria, p_material, p_alto_cm, p_ancho_cm, p_profundidad_cm, p_color, p_peso_gramos, p_foto_url, p_precio, p_stock);
        INSERT INTO HISTORIAL_PRECIOS (ID_MUEBLE, PRECIO) VALUES ((SELECT ID_MUEBLE FROM MUEBLES WHERE REFERENCIA = p_referencia), p_precio);
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END PR_CREAR_MUEBLE;

    PROCEDURE PR_OBTENER_MUEBLE(p_id_mueble IN NUMBER, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
        SELECT M.ID_MUEBLE, M.REFERENCIA, M.NOMBRE, M.DESCRIPCION, M.TIPO, M.MATERIAL, M.ALTO_CM, M.ANCHO_CM, M.PROFUNDIDAD_CM,
               M.COLOR, M.PESO_GRAMOS, M.FOTO_URL, M.PRECIO_VENTA, M.STOCK_DISPONIBLE, C.NOMBRE AS CATEGORIA, M.ID_CATEGORIA
        FROM MUEBLES M LEFT JOIN CATEGORIAS C ON M.ID_CATEGORIA = C.ID_CATEGORIA WHERE M.ID_MUEBLE = p_id_mueble;
    END PR_OBTENER_MUEBLE;

    PROCEDURE PR_MODIFICAR_MUEBLE(
        p_id_mueble IN NUMBER, p_referencia IN VARCHAR2, p_nombre IN VARCHAR2, p_descripcion IN CLOB, p_tipo IN VARCHAR2, p_id_categoria IN NUMBER,
        p_material IN VARCHAR2, p_alto_cm IN NUMBER, p_ancho_cm IN NUMBER, p_profundidad_cm IN NUMBER, p_color IN VARCHAR2, p_peso_gramos IN NUMBER, p_foto_url IN VARCHAR2
    ) IS
    BEGIN
        UPDATE MUEBLES SET REFERENCIA = p_referencia, NOMBRE = p_nombre, DESCRIPCION = p_descripcion, TIPO = p_tipo, ID_CATEGORIA = p_id_categoria, MATERIAL = p_material,
            ALTO_CM = p_alto_cm, ANCHO_CM = p_ancho_cm, PROFUNDIDAD_CM = p_profundidad_cm, COLOR = p_color, PESO_GRAMOS = p_peso_gramos, FOTO_URL = p_foto_url
        WHERE ID_MUEBLE = p_id_mueble;
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20010, 'Mueble no encontrado'); END IF;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END PR_MODIFICAR_MUEBLE;

    PROCEDURE PR_ACTUALIZAR_PRECIO_STOCK(p_id_mueble IN NUMBER, p_precio IN NUMBER, p_stock IN NUMBER) IS
        v_precio_anterior NUMBER;
    BEGIN
        SELECT PRECIO_VENTA INTO v_precio_anterior FROM MUEBLES WHERE ID_MUEBLE = p_id_mueble;
        UPDATE MUEBLES SET PRECIO_VENTA = p_precio, STOCK_DISPONIBLE = p_stock WHERE ID_MUEBLE = p_id_mueble;
        IF v_precio_anterior <> p_precio THEN INSERT INTO HISTORIAL_PRECIOS (ID_MUEBLE, PRECIO) VALUES (p_id_mueble, p_precio); END IF;
        IF p_stock > 0 THEN INSERT INTO INVENTARIO_MOVIMIENTOS (ID_MUEBLE, TIPO_MOVIMIENTO, CANTIDAD, DESCRIPCION) VALUES (p_id_mueble, 'ENTRADA', p_stock, 'Actualización de stock admin'); END IF;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END PR_ACTUALIZAR_PRECIO_STOCK;

    PROCEDURE PR_ELIMINAR_MUEBLE(p_id_mueble IN NUMBER) IS
        v_compras NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_compras FROM DETALLE_COMPRA WHERE ID_MUEBLE = p_id_mueble;
        IF v_compras > 0 THEN RAISE_APPLICATION_ERROR(-20011, 'No se puede eliminar: el mueble ha sido comprado por clientes'); END IF;
        DELETE FROM DETALLE_CARRITO WHERE ID_MUEBLE = p_id_mueble;
        DELETE FROM HISTORIAL_PRECIOS WHERE ID_MUEBLE = p_id_mueble;
        DELETE FROM INVENTARIO_MOVIMIENTOS WHERE ID_MUEBLE = p_id_mueble;
        DELETE FROM MUEBLES WHERE ID_MUEBLE = p_id_mueble;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
    END PR_ELIMINAR_MUEBLE;

    PROCEDURE PR_LISTAR_CATEGORIAS(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR SELECT ID_CATEGORIA, NOMBRE FROM CATEGORIAS ORDER BY NOMBRE;
    END PR_LISTAR_CATEGORIAS;
END PKG_MUEBLES;
